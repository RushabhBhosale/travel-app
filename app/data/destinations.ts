const MONTHS = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"];

/** Whether `month` (0–11) falls in a destination's best time, e.g. "Oct – Mar" or "Sep – Nov, Feb – May". */
export function inSeason(d: Destination, month: number) {
  return d.bestTime.split(",").some((range) => {
    const [from, to] = range.split("–").map((m) => MONTHS.indexOf(m.trim().slice(0, 3).toLowerCase()));
    if (from < 0) return false;
    const end = to < 0 ? from : to;
    return from <= end ? month >= from && month <= end : month >= from || month <= end;
  });
}

export const destinationById = (id?: string) => DESTINATIONS.find((d) => d.id === id);

/** Bundled destination image, if a trip name matches a curated destination. */
export function matchDestination(name: string) {
  const n = name.toLowerCase();
  return DESTINATIONS.find(
    (d) => n.includes(d.name.toLowerCase()) || n.includes(d.wiki.toLowerCase()) || n.startsWith(d.id)
  );
}
